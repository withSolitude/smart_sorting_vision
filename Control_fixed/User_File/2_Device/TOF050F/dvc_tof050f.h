#ifndef DVC_TOF050F_H
#define DVC_TOF050F_H


#include "main.h"


// ============================================================
// TOF050F状态
// ============================================================

enum Enum_TOF050F_Status
{
    TOF050F_Status_DISABLE = 0,

    TOF050F_Status_ENABLE,

    TOF050F_Status_ERROR,
};


// ============================================================
// TOF050F测距模式
//
// 规格书：
//
// 1：高精度    0.2m
// 2：中距离    0.4m
// 3：长距离    0.5m
// ============================================================

enum Enum_TOF050F_Range_Mode : uint16_t
{
    TOF050F_Range_Mode_High_Precision = 0x0001,

    TOF050F_Range_Mode_Middle =
        0x0002,

    TOF050F_Range_Mode_Long =
        0x0003,
};


// ============================================================
// TOF050F数据
// ============================================================

struct Struct_TOF050F_Data
{
    // ========================================================
    // 测距值
    //
    // 单位：mm
    // ========================================================

    uint16_t Distance_mm = 0;


    // ========================================================
    // 当前距离数据是否有效
    // ========================================================

    bool Distance_Valid = false;


    // ========================================================
    // 传感器是否在线
    // ========================================================

    bool Online = false;


    // ========================================================
    // 正确接收帧数量
    // ========================================================

    uint32_t Rx_Count = 0;


    // ========================================================
    // CRC错误数量
    // ========================================================

    uint32_t CRC_Error_Count = 0;


    // ========================================================
    // 数据帧格式错误数量
    // ========================================================

    uint32_t Frame_Error_Count = 0;


    // ========================================================
    // 通信超时数量
    // ========================================================

    uint32_t Timeout_Count = 0;
};


// ============================================================
// TOF050F
// ============================================================

class Class_TOF050F
{
public:

    // ========================================================
    // 初始化
    //
    // huart：
    //      TOF050F使用的UART
    //
    // Device_Address：
    //      Modbus从机地址
    //
    //      默认0x01
    // ========================================================

    void Init(
        UART_HandleTypeDef *huart,
        uint8_t Device_Address = 0x01
    );


    // ========================================================
    // 主动读取一次距离
    //
    // 实际发送：
    //
    // 01 03 00 10 00 01 CRC_L CRC_H
    //
    // 非阻塞DMA发送
    // ========================================================

    HAL_StatusTypeDef Request_Distance();


    // ========================================================
    // 设置测距模式
    //
    // 1 高精度
    // 2 中距离
    // 3 长距离
    // ========================================================

    HAL_StatusTypeDef Set_Range_Mode(
        Enum_TOF050F_Range_Mode Range_Mode
    );


    // ========================================================
    // 设置自动输出周期
    //
    // 0：
    //      不自动输出
    //
    // 例如：
    //      100 -> 100ms
    //      500 -> 500ms
    //
    // 目前本驱动推荐使用：
    //
    // Auto_Output_Period = 0
    //
    // 然后由STM32主动每100ms Request_Distance()
    // ========================================================

    HAL_StatusTypeDef Set_Auto_Output_Period(
        uint16_t Period_ms
    );


    // ========================================================
    // 加载校准
    //
    // true  -> 加载
    // false -> 不加载
    // ========================================================

    HAL_StatusTypeDef Set_Load_Calibration(
        bool Enable
    );


    // ========================================================
    // 修改设备地址
    //
    // 注意：
    //
    // 0是广播地址
    //
    // 正常单模块建议：
    // 1 ~ 247
    // ========================================================

    HAL_StatusTypeDef Set_Device_Address(
        uint8_t New_Address
    );


    // ========================================================
    // 模块重启
    // ========================================================

    HAL_StatusTypeDef Restart();


    // ========================================================
    // 恢复默认参数
    // ========================================================

    HAL_StatusTypeDef Restore_Default();


    // ========================================================
    // UART接收回调
    //
    // 放到你现有UART管理层的回调里面
    // ========================================================

    void UART_RxCpltCallback(
        uint8_t *Buffer,
        uint16_t Length
    );


    // ========================================================
    // 100ms定时任务
    //
    // 建议：
    //
    // 每100ms调用一次
    // 自动请求距离
    // ========================================================

    void TIM_100ms_PeriodElapsedCallback();


    // ========================================================
    // 是否开启自动主动读取
    // ========================================================

    inline void Set_Auto_Request(
        bool Enable)
    {
        Auto_Request_Enable =
            Enable;
    }


    // ========================================================
    // 获取距离
    // ========================================================

    inline uint16_t Get_Distance_mm() const
    {
        return Data.Distance_mm;
    }


    // ========================================================
    // 获取数据有效状态
    // ========================================================

    inline bool Get_Distance_Valid() const
    {
        return Data.Distance_Valid;
    }


    // ========================================================
    // 获取在线状态
    // ========================================================

    inline bool Get_Online() const
    {
        return Data.Online;
    }


    // ========================================================
    // 获取完整数据
    // ========================================================

    inline const Struct_TOF050F_Data &
    Get_Data() const
    {
        return Data;
    }


    // ========================================================
    // 获取设备地址
    // ========================================================

    inline uint8_t Get_Device_Address() const
    {
        return Device_Address;
    }


    // ========================================================
    // 获取状态
    // ========================================================

    inline Enum_TOF050F_Status
    Get_Status() const
    {
        return Status;
    }


private:

    // ========================================================
    // UART
    // ========================================================

    UART_HandleTypeDef *UART_Handler =
        nullptr;


    // ========================================================
    // Modbus设备地址
    // ========================================================

    uint8_t Device_Address =
        0x01;


    // ========================================================
    // DMA发送Buffer
    //
    // Modbus 03 / 06指令都是8字节
    // ========================================================

    uint8_t Tx_Buffer[8] =
        {0};


    // ========================================================
    // 数据
    // ========================================================

    Struct_TOF050F_Data Data;


    // ========================================================
    // 模块状态
    // ========================================================

    Enum_TOF050F_Status Status =
        TOF050F_Status_DISABLE;


    // ========================================================
    // 是否等待模块回复
    // ========================================================

    bool Waiting_Response =
        false;


    // ========================================================
    // 等待回复的100ms计数
    // ========================================================

    uint8_t Response_Timeout_Count =
        0;


    // ========================================================
    // 连续掉线计数
    // ========================================================

    uint8_t Offline_Count =
        0;


    // ========================================================
    // 自动主动读取
    // ========================================================

    bool Auto_Request_Enable =
        true;


    // ========================================================
    // 修改ID时使用
    // ========================================================

    bool Pending_Address_Change =
        false;


    uint8_t Pending_New_Address =
        0x01;


    // ========================================================
    // Modbus CRC16
    // ========================================================

    uint16_t Calculate_CRC16(
        const uint8_t *Data,
        uint16_t Length
    ) const;


    // ========================================================
    // 读取Holding Register
    //
    // Function = 0x03
    // ========================================================

    HAL_StatusTypeDef
    Read_Holding_Register(
        uint16_t Register_Address,
        uint16_t Register_Number
    );


    // ========================================================
    // 写单寄存器
    //
    // Function = 0x06
    // ========================================================

    HAL_StatusTypeDef
    Write_Single_Register(
        uint16_t Register_Address,
        uint16_t Register_Data
    );


    // ========================================================
    // 发送8字节Modbus帧
    // ========================================================

    HAL_StatusTypeDef
    Transmit_Frame();


    // ========================================================
    // 解析03响应
    // ========================================================

    bool Parse_Read_Response(
        const uint8_t *Buffer,
        uint16_t Length
    );


    // ========================================================
    // 解析06响应
    // ========================================================

    bool Parse_Write_Response(
        const uint8_t *Buffer,
        uint16_t Length
    );


    // ========================================================
    // CRC检查
    // ========================================================

    bool Check_CRC(
        const uint8_t *Buffer,
        uint16_t Length
    ) const;
};


#endif // DVC_TOF050F_H