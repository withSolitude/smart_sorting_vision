from __future__ import annotations

import argparse
from pathlib import Path

import torch
from ultralytics import YOLO


# ============================================================
# 工程根目录
# ============================================================

ROOT = (
    Path(__file__)
    .resolve()
    .parents[2]
)


# ============================================================
# V2正式数据集
# ============================================================

DATASET_YAML = (
    ROOT
    / "data"
    / "datasets"
    / "top_seg"
    / "prepared"
    / "v2"
    / "data.yaml"
)


# ============================================================
# V1正式模型
#
# V2不从官方COCO模型重新开始。
#
# 使用：
#
# V1 best.pt
#     ↓
# V1 + V2数据
#     ↓
# Fine-tune V2
# ============================================================

V1_MODEL = (
    ROOT
    / "weights"
    / "top_seg"
    / "v1"
    / "best.pt"
)


# ============================================================
# 输出目录
# ============================================================

PROJECT_DIR = (
    ROOT
    / "outputs"
    / "training"
    / "top_seg"
    / "v2"
)


# ============================================================
# 基础训练参数
# ============================================================

IMAGE_SIZE = 832

EPOCHS = 120

PATIENCE = 30

SEED = 2026

WORKERS = 4


# ============================================================
# 打印设备
# ============================================================

def get_device():

    if torch.cuda.is_available():

        device = 0

        device_name = (
            torch.cuda.get_device_name(0)
        )

        return (
            device,
            device_name,
            True,
        )

    return (
        "cpu",
        "CPU",
        False,
    )


# ============================================================
# Baseline增强参数
#
# 这里是真正意义上的：
#
# NO AUGMENTATION
#
# 特别注意：
# Ultralytics本身有默认数据增强。
#
# 所以如果什么都不写，
# 并不等于没有数据增强。
#
# 为了做严格对照实验，
# 这里全部明确关闭。
# ============================================================

def get_baseline_augmentation():

    return {

        # -------------------------
        # HSV
        # -------------------------

        "hsv_h": 0.0,

        "hsv_s": 0.0,

        "hsv_v": 0.0,

        # -------------------------
        # 几何
        # -------------------------

        "degrees": 0.0,

        "translate": 0.0,

        "scale": 0.0,

        "shear": 0.0,

        "perspective": 0.0,

        # -------------------------
        # 翻转
        # -------------------------

        "flipud": 0.0,

        "fliplr": 0.0,

        # -------------------------
        # 组合增强
        # -------------------------

        "mosaic": 0.0,

        "mixup": 0.0,

        "cutmix": 0.0,

        # -------------------------
        # Segmentation Copy-Paste
        # -------------------------

        "copy_paste": 0.0,

        # -------------------------
        # BGR交换
        # -------------------------

        "bgr": 0.0,
    }


# ============================================================
# V2正式增强方案
#
# 针对：
#
# 固定顶部相机
# 固定托盘
# 固定ROI
# 固定光照系统
#
# 因此：
#
# 不进行大角度旋转
# 不翻转整个场景
# 不Mosaic
# 不Perspective
#
# 只模拟真实运行中可能发生的：
#
# 光照变化
# 小角度姿态变化
# 小位置变化
# 小尺度变化
# Instance Copy-Paste
# ============================================================

def get_augmented_augmentation():

    return {

        # ====================================================
        # 1. 色彩 / 照明
        # ====================================================

        "hsv_h": 0.008,

        "hsv_s": 0.20,

        "hsv_v": 0.18,

        # ====================================================
        # 2. 小角度旋转
        # ====================================================

        "degrees": 3.0,

        # ====================================================
        # 3. 小范围平移
        # ====================================================

        "translate": 0.03,

        # ====================================================
        # 4. 小范围缩放
        # ====================================================

        "scale": 0.10,

        # ====================================================
        # 不使用不符合实际场景的几何变化
        # ====================================================

        "shear": 0.0,

        "perspective": 0.0,

        # ====================================================
        # 固定工业相机
        #
        # 不翻转整个托盘画面
        # ====================================================

        "flipud": 0.0,

        "fliplr": 0.0,

        # ====================================================
        # 不使用Mosaic
        #
        # Mosaic会产生多个托盘拼在一起的假图。
        # ====================================================

        "mosaic": 0.0,

        # ====================================================
        # 暂时不使用MixUp和CutMix
        # ====================================================

        "mixup": 0.0,

        "cutmix": 0.0,

        # ====================================================
        # 实例分割专用增强
        #
        # 低概率使用即可。
        # ====================================================

        "copy_paste": 0.15,

        "copy_paste_mode": "mixup",

        # ====================================================
        # 不随机交换BGR通道
        # ====================================================

        "bgr": 0.0,
    }


# ============================================================
# Main
# ============================================================

def main():

    parser = argparse.ArgumentParser(
        description=(
            "Train Top Camera YOLO Segmentation V2"
        )
    )

    parser.add_argument(
        "--mode",
        choices=[
            "baseline",
            "aug",
        ],
        required=True,
        help=(
            "baseline = 不使用数据增强；"
            "aug = 使用V2正式数据增强。"
        ),
    )

    parser.add_argument(
        "--epochs",
        type=int,
        default=EPOCHS,
    )

    parser.add_argument(
        "--imgsz",
        type=int,
        default=IMAGE_SIZE,
    )

    args = parser.parse_args()

    # ========================================================
    # 文件检查
    # ========================================================

    if not DATASET_YAML.exists():

        raise FileNotFoundError(
            "找不到V2数据集：\n"
            f"{DATASET_YAML}"
        )

    if not V1_MODEL.exists():

        raise FileNotFoundError(
            "找不到V1 best.pt：\n"
            f"{V1_MODEL}"
        )

    # ========================================================
    # GPU
    # ========================================================

    (
        device,
        device_name,
        cuda_available,
    ) = get_device()

    # ========================================================
    # 你的正式训练建议使用GPU
    # ========================================================

    if not cuda_available:

        raise RuntimeError(
            "当前没有检测到CUDA GPU。\n"
            "正式V2训练建议先解决PyTorch CUDA环境，"
            "不要直接用CPU训练。"
        )

    # ========================================================
    # Mode
    # ========================================================

    if args.mode == "baseline":

        run_name = (
            "v2_baseline_no_aug"
        )

        augmentation = (
            get_baseline_augmentation()
        )

    else:

        run_name = (
            "v2_aug"
        )

        augmentation = (
            get_augmented_augmentation()
        )

    # ========================================================
    # 信息
    # ========================================================

    print()

    print(
        "============================================================"
    )

    print(
        "TOP SEG V2 TRAINING"
    )

    print(
        "============================================================"
    )

    print(
        f"Mode:"
        f"     {args.mode}"
    )

    print(
        f"Dataset:"
        f"  {DATASET_YAML}"
    )

    print(
        f"Init:"
        f"     {V1_MODEL}"
    )

    print(
        f"Device:"
        f"   {device_name}"
    )

    print(
        f"Image:"
        f"    {args.imgsz}"
    )

    print(
        f"Epochs:"
        f"   {args.epochs}"
    )

    print(
        f"Seed:"
        f"     {SEED}"
    )

    print(
        f"Run:"
        f"      {run_name}"
    )

    print()

    print(
        "Augmentation:"
    )

    for key, value in (
        augmentation.items()
    ):

        print(
            f"  {key:<20} = {value}"
        )

    print(
        "============================================================"
    )

    # ========================================================
    # 加载V1 best.pt
    # ========================================================

    model = YOLO(
        str(
            V1_MODEL
        )
    )

    # ========================================================
    # V2训练
    # ========================================================

    model.train(

        # ----------------------------------------------------
        # 数据
        # ----------------------------------------------------

        data=str(
            DATASET_YAML
        ),

        # ----------------------------------------------------
        # 训练规模
        # ----------------------------------------------------

        epochs=args.epochs,

        imgsz=args.imgsz,

        # ----------------------------------------------------
        # 自动选择GPU batch
        # ----------------------------------------------------

        batch=-1,

        device=device,

        workers=WORKERS,

        # ----------------------------------------------------
        # Fine-tune
        # ----------------------------------------------------

        pretrained=True,

        resume=False,

        # ----------------------------------------------------
        # 优化器
        #
        # baseline与aug保持完全一致
        # ----------------------------------------------------

        optimizer="auto",

        # ----------------------------------------------------
        # 可重复性
        # ----------------------------------------------------

        seed=SEED,

        deterministic=True,

        # ----------------------------------------------------
        # Early Stopping
        # ----------------------------------------------------

        patience=PATIENCE,

        # ----------------------------------------------------
        # GPU Mixed Precision
        # ----------------------------------------------------

        amp=True,

        # ----------------------------------------------------
        # Validation
        # ----------------------------------------------------

        val=True,

        plots=True,

        # ----------------------------------------------------
        # 保存
        # ----------------------------------------------------

        save=True,

        save_period=10,

        project=str(
            PROJECT_DIR
        ),

        name=run_name,

        # 防止误覆盖之前结果
        exist_ok=False,

        # ----------------------------------------------------
        # 数据不全部缓存内存
        # ----------------------------------------------------

        cache=False,

        # ----------------------------------------------------
        # Segmentation
        # ----------------------------------------------------

        overlap_mask=True,

        mask_ratio=4,

        # ----------------------------------------------------
        # augmentation
        # ----------------------------------------------------

        **augmentation,
    )


if __name__ == "__main__":

    main()