from __future__ import annotations

from pathlib import Path

import torch
from ultralytics import YOLO


# ============================================================
# 项目根目录
# ============================================================

ROOT = (
    Path(__file__)
    .resolve()
    .parents[2]
)


# ============================================================
# 数据集
# ============================================================

DATASET_YAML = (
    ROOT
    / "data"
    / "datasets"
    / "top_seg"
    / "prepared"
    / "v1"
    / "data.yaml"
)


# ============================================================
# 训练输出目录
# ============================================================

PROJECT_DIR = (
    ROOT
    / "outputs"
    / "training"
    / "top_seg"
)


# ============================================================
# V1实验名称
# ============================================================

RUN_NAME = "v1_yolo26n_seg_832"


# ============================================================
# 模型
#
# 第一次使用时 Ultralytics 会下载官方预训练权重
# ============================================================

MODEL_NAME = "yolo26n-seg.pt"


# ============================================================
# 训练参数
# ============================================================

IMAGE_SIZE = 832

EPOCHS = 150

PATIENCE = 40

SEED = 2026


def main():

    # ========================================================
    # 1. 检查数据集
    # ========================================================

    if not DATASET_YAML.exists():

        raise FileNotFoundError(
            f"找不到数据集：\n"
            f"{DATASET_YAML}\n\n"
            "请先完成 prepared/v1 数据集生成。"
        )

    # ========================================================
    # 2. 自动选择训练设备
    # ========================================================

    if torch.cuda.is_available():

        device = 0

        # Ultralytics AutoBatch
        batch = -1

        amp = True

        device_name = torch.cuda.get_device_name(0)

    else:

        device = "cpu"

        # CPU训练使用较小batch
        batch = 4

        amp = False

        device_name = "CPU"

    print(
        "============================================================"
    )

    print(
        "TOP CAMERA SEGMENTATION TRAINING"
    )

    print(
        "============================================================"
    )

    print(
        f"Dataset : {DATASET_YAML}"
    )

    print(
        f"Model   : {MODEL_NAME}"
    )

    print(
        f"Device  : {device_name}"
    )

    print(
        f"imgsz   : {IMAGE_SIZE}"
    )

    print(
        f"epochs  : {EPOCHS}"
    )

    print(
        f"batch   : {batch}"
    )

    print(
        f"seed    : {SEED}"
    )

    print(
        "============================================================"
    )

    # ========================================================
    # 3. 加载预训练实例分割模型
    # ========================================================

    model = YOLO(
        MODEL_NAME
    )

    # ========================================================
    # 4. 开始训练
    #
    # 当前项目特点：
    #
    # - 固定顶部相机
    # - 固定托盘
    # - 固定曝光/白平衡
    # - 固定 SAFE ROI
    #
    # 因此第一版不使用过强的数据增强。
    # ========================================================

    model.train(

        # ----------------------------------------------------
        # Dataset
        # ----------------------------------------------------

        data=str(
            DATASET_YAML
        ),

        # ----------------------------------------------------
        # Basic training
        # ----------------------------------------------------

        epochs=EPOCHS,

        imgsz=IMAGE_SIZE,

        batch=batch,

        device=device,

        workers=4,

        # ----------------------------------------------------
        # Transfer learning
        # ----------------------------------------------------

        pretrained=True,

        optimizer="auto",

        # ----------------------------------------------------
        # Reproducibility
        # ----------------------------------------------------

        seed=SEED,

        deterministic=True,

        # ----------------------------------------------------
        # Early stopping
        # ----------------------------------------------------

        patience=PATIENCE,

        # ----------------------------------------------------
        # AMP
        # ----------------------------------------------------

        amp=amp,

        # ----------------------------------------------------
        # Validation
        # ----------------------------------------------------

        val=True,

        plots=True,

        # ----------------------------------------------------
        # Save
        # ----------------------------------------------------

        save=True,

        save_period=10,

        project=str(
            PROJECT_DIR
        ),

        name=RUN_NAME,

        exist_ok=False,

        # ----------------------------------------------------
        # Cache
        # ----------------------------------------------------

        cache=False,

        # ----------------------------------------------------
        # 数据增强
        #
        # 相机和托盘是固定的，因此不使用太激进的几何增强。
        # ----------------------------------------------------

        hsv_h=0.005,

        hsv_s=0.20,

        hsv_v=0.15,

        degrees=0.0,

        translate=0.02,

        scale=0.10,

        shear=0.0,

        perspective=0.0,

        flipud=0.0,

        fliplr=0.0,

        # ----------------------------------------------------
        # Mosaic
        #
        # 对固定托盘场景，第一版关闭。
        #
        # 否则可能产生四个托盘拼接的非真实场景。
        # ----------------------------------------------------

        mosaic=0.0,

        mixup=0.0,

        copy_paste=0.0,

        # ----------------------------------------------------
        # Segmentation
        # ----------------------------------------------------

        overlap_mask=True,

        mask_ratio=4,
    )


if __name__ == "__main__":

    main()